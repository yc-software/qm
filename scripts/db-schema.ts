import { execFile } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import pg from "pg";

const run = promisify(execFile);
const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SCHEMA_FILE = join(ROOT, "db/schema.sql");
const OWNED_ELSEWHERE = ["pgboss"];
const HEADER = `-- Generated by \`npm run db:schema\` from a database migrated from empty. Do not edit.
-- CI fails when this file differs from what the migrations produce.
`;

const DUMP_NOISE = [
  "-- Name: ",
  "-- PostgreSQL database dump",
  "-- Dumped ",
  "SET ",
  "SELECT pg_catalog.set_config",
  "\\restrict ",
  "\\unrestrict ",
];

function normalizeDump(dump: string): string {
  const lines: string[] = [];
  for (const raw of dump.split("\n")) {
    const line = raw.trimEnd();
    if (line === "--" || DUMP_NOISE.some((prefix) => line.startsWith(prefix))) continue;
    if (line === "" && (lines.length === 0 || lines.at(-1) === "")) continue;
    lines.push(line);
  }
  while (lines.at(-1) === "") lines.pop();
  return `${HEADER}\n${lines.join("\n")}\n`;
}

async function dumpSchema(baseUrl: string): Promise<string> {
  const scratch = `qm_schema_${randomBytes(4).toString("hex")}`;
  const scratchUrl = new URL(baseUrl);
  scratchUrl.pathname = `/${scratch}`;
  const admin = new pg.Client({ connectionString: baseUrl });
  await admin.connect();
  try {
    const server = String((await admin.query("SHOW server_version_num")).rows[0].server_version_num).slice(0, -4);
    const packaged = `/usr/lib/postgresql/${server}/bin/pg_dump`;
    const pgDump = process.env.PG_DUMP ?? (existsSync(packaged) ? packaged : "pg_dump");
    const client = (await run(pgDump, ["--version"])).stdout.split(" ")[2]?.split(".")[0];
    if (server !== client) {
      throw new Error(
        `${pgDump} is version ${client}; dumps differ across versions, so set PG_DUMP to a ${server} pg_dump`,
      );
    }
    await admin.query(`CREATE DATABASE ${scratch}`);
    await run(process.execPath, ["src/migrate-main.ts"], {
      cwd: ROOT,
      env: {
        PATH: process.env.PATH,
        HOME: process.env.HOME,
        DATABASE_URL: scratchUrl.href,
        CONNECTOR_SECRET_KEY: randomBytes(32).toString("hex"),
      },
      maxBuffer: Infinity,
    });
    const exclude = OWNED_ELSEWHERE.map((schema) => `--exclude-schema=${schema}`);
    const { stdout } = await run(
      pgDump,
      ["--schema-only", "--no-owner", "--no-privileges", ...exclude, scratchUrl.href],
      {
        maxBuffer: Infinity,
      },
    );
    return normalizeDump(stdout);
  } finally {
    await admin.query(`DROP DATABASE IF EXISTS ${scratch} WITH (FORCE)`).catch((error: unknown) => {
      console.error(`[db:schema] could not drop scratch database ${scratch}:`, error);
    });
    await admin.end();
  }
}

const baseUrl = process.env.DATABASE_URL;
if (!baseUrl) {
  console.error("Set DATABASE_URL to a Postgres server with pgvector where a scratch database may be created");
  process.exit(2);
}
await writeFile(SCHEMA_FILE, await dumpSchema(baseUrl));
console.log("[db:schema] wrote db/schema.sql");
