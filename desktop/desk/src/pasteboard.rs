use crate::protocol::{ErrorCode, Failure, PasteFormat};
use crate::text;
use core_foundation::runloop::{kCFRunLoopDefaultMode, CFRunLoop};
use objc2::rc::Retained;
use objc2::runtime::{NSObject, NSObjectProtocol, ProtocolObject};
use objc2::{define_class, msg_send, AnyThread, DefinedClass};
use objc2_app_kit::{
    NSPasteboard, NSPasteboardItem, NSPasteboardItemDataProvider, NSPasteboardType, NSPasteboardTypeHTML, NSPasteboardTypeString,
    NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSString};
use std::sync::Mutex;
use std::time::{Duration, Instant};

const MARKERS: &[&str] = &["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
const CONCEALED: &[&str] = &["org.nspasteboard.ConcealedType"];
const READ_TIMEOUT: Duration = Duration::from_secs(3);
const MORE_READS: Duration = Duration::from_millis(250);
const SHOW_TIMEOUT: Duration = Duration::from_millis(1500);
const CHECK_EVERY: Duration = Duration::from_millis(100);

pub struct Payload {
    data: Vec<(String, Vec<u8>)>,
    last: Mutex<Option<Instant>>,
}

define_class!(
    #[unsafe(super(NSObject))]
    #[name = "QMDeskPasteProvider"]
    #[ivars = Payload]
    struct Provider;

    unsafe impl NSObjectProtocol for Provider {}

    unsafe impl NSPasteboardItemDataProvider for Provider {
        #[unsafe(method(pasteboard:item:provideDataForType:))]
        fn provide(&self, _board: Option<&NSPasteboard>, item: &NSPasteboardItem, kind: &NSPasteboardType) {
            let name = kind.to_string();
            if let Some((_, bytes)) = self.ivars().data.iter().find(|(t, _)| *t == name) {
                item.setData_forType(&NSData::with_bytes(bytes), kind);
                *self.ivars().last.lock().unwrap_or_else(|e| e.into_inner()) = Some(Instant::now());
            }
        }
    }
);

impl Provider {
    fn new(data: Vec<(String, Vec<u8>)>) -> Retained<Self> {
        let this = Self::alloc().set_ivars(Payload { data, last: Mutex::new(None) });
        unsafe { msg_send![super(this), init] }
    }

    fn last_read(&self) -> Option<Instant> {
        *self.ivars().last.lock().unwrap_or_else(|e| e.into_inner())
    }
}

type Saved = Vec<Vec<(Retained<NSString>, Retained<NSData>)>>;

fn fail(code: ErrorCode, m: &str) -> Failure {
    Failure::new(code, m)
}

fn snapshot(board: &NSPasteboard) -> Result<Saved, Failure> {
    let before = board.changeCount();
    let mut saved = vec![];
    for item in board.pasteboardItems().iter().flat_map(|items| items.iter()) {
        let mut types = vec![];
        for t in item.types() {
            if CONCEALED.contains(&t.to_string().as_str()) {
                return Err(fail(
                    ErrorCode::ActionFailed,
                    "The clipboard holds a concealed item, such as a password, so desk did not paste. Use typeText instead.",
                ));
            }
            let d = item
                .dataForType(&t)
                .ok_or_else(|| fail(ErrorCode::ActionFailed, "Could not preserve the current clipboard; paste was not attempted."))?;
            types.push((t, d));
        }
        saved.push(types);
    }
    if board.changeCount() != before {
        return Err(fail(ErrorCode::PasteConflict, "The clipboard changed while being saved; paste was not attempted."));
    }
    Ok(saved)
}

fn write(board: &NSPasteboard, items: Vec<Retained<NSPasteboardItem>>) -> bool {
    board.clearContents();
    if items.is_empty() {
        return true;
    }
    let objects: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = items.into_iter().map(ProtocolObject::from_retained).collect();
    board.writeObjects(&NSArray::from_retained_slice(&objects))
}

fn restore(board: &NSPasteboard, saved: &Saved) -> bool {
    let items = saved
        .iter()
        .map(|types| {
            let item = NSPasteboardItem::new();
            for (t, d) in types {
                item.setData_forType(d, t);
            }
            item
        })
        .collect();
    write(board, items)
}

pub enum Check {
    Landed,
    NotYet,
    Unreadable,
}

const CONFLICT: &str = "The clipboard changed during the paste, probably because the user copied something. \
The app may have pasted that instead of your text. Observe the app and check what was pasted before continuing.";

fn uncertain(board: &NSPasteboard, ours: isize, data: &[(String, Vec<u8>)], why: &str) -> Failure {
    if board.changeCount() != ours {
        return fail(ErrorCode::PasteConflict, CONFLICT);
    }
    let item = NSPasteboardItem::new();
    for marker in MARKERS {
        item.setData_forType(&NSData::new(), &NSString::from_str(marker));
    }
    for (t, d) in data {
        item.setData_forType(&NSData::with_bytes(d), &NSString::from_str(t));
    }
    let kept = if write(board, vec![item]) {
        "The pasted text is still on the clipboard"
    } else {
        "desk could not keep the pasted text on the clipboard"
    };
    fail(
        ErrorCode::ActionFailed,
        &format!(
            "desk could not confirm that the app pasted the text: {why}. {kept}, and the user's previous clipboard was not restored, \
because restoring it now could let the app paste that instead. Observe the field to check what was pasted before continuing."
        ),
    )
}

pub fn paste(
    text: &str,
    format: PasteFormat,
    keystroke: impl FnOnce() -> Result<(), Failure>,
    check: &mut dyn FnMut() -> Check,
    interrupted: &dyn Fn() -> Result<(), Failure>,
) -> Result<(), Failure> {
    let (plain, html) = text::payload(text, format);
    let mut data = vec![(unsafe { NSPasteboardTypeString }.to_string(), plain.into_bytes())];
    if let Some(html) = html {
        data.push((unsafe { NSPasteboardTypeHTML }.to_string(), html.into_bytes()));
    }
    let types: Vec<Retained<NSString>> = data.iter().map(|(t, _)| NSString::from_str(t)).collect();
    let provider = Provider::new(data.clone());
    let item = NSPasteboardItem::new();
    for marker in MARKERS {
        item.setData_forType(&NSData::new(), &NSString::from_str(marker));
    }
    if !item.setDataProvider_forTypes(ProtocolObject::from_ref(&*provider), &NSArray::from_retained_slice(&types)) {
        return Err(fail(ErrorCode::ActionFailed, "Could not put the text on the clipboard."));
    }

    let board = NSPasteboard::generalPasteboard();
    let saved = snapshot(&board)?;
    if !write(&board, vec![item]) {
        return Err(fail(
            ErrorCode::ActionFailed,
            if restore(&board, &saved) {
                "Could not put the text on the clipboard."
            } else {
                "Could not put the text on the clipboard, and the previous clipboard could not be restored."
            },
        ));
    }
    let ours = board.changeCount();
    if let Err(e) = keystroke() {
        return Err(uncertain(&board, ours, &data, &format!("sending Cmd+V failed ({})", e.message)));
    }

    let start = Instant::now();
    let mut checked = start;
    let mut landed = false;
    loop {
        CFRunLoop::run_in_mode(unsafe { kCFRunLoopDefaultMode }, Duration::from_millis(20), true);
        if board.changeCount() != ours {
            return Err(fail(ErrorCode::PasteConflict, CONFLICT));
        }
        if let Err(e) = interrupted() {
            return Err(uncertain(&board, ours, &data, &format!("the paste was interrupted after Cmd+V was sent ({})", e.message)));
        }
        let Some(read) = provider.last_read() else {
            if start.elapsed() >= READ_TIMEOUT {
                return Err(uncertain(&board, ours, &data, "no app read the clipboard within 3 s of Cmd+V"));
            }
            continue;
        };
        if !landed && checked.elapsed() >= CHECK_EVERY {
            checked = Instant::now();
            match check() {
                Check::Landed => landed = true,
                Check::NotYet => {}
                Check::Unreadable if read.elapsed() >= MORE_READS => {
                    return Err(uncertain(&board, ours, &data, "desk cannot read the text of the app's focused field"))
                }
                Check::Unreadable => {}
            }
        }
        if landed && read.elapsed() >= MORE_READS {
            break;
        }
        if !landed && (read.elapsed() >= SHOW_TIMEOUT || start.elapsed() >= READ_TIMEOUT * 2) {
            return Err(uncertain(&board, ours, &data, "the clipboard was read, but the focused field does not show the pasted text"));
        }
    }
    if board.changeCount() != ours || !restore(&board, &saved) {
        return Err(fail(
            ErrorCode::ActionFailed,
            "The text was pasted, but the previous clipboard could not be restored. Check the clipboard before continuing.",
        ));
    }
    Ok(())
}
