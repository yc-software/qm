function storedLocale(): string | null {
  try {
    return globalThis.localStorage?.getItem(LOCALE_KEY) ?? null;
  } catch {
    return null;
  }
}

function browserLanguages(): readonly string[] {
  if (typeof navigator === "undefined") return [];
  if (navigator.languages?.length) return navigator.languages;
  return [navigator.language];
}

export function resolveLocale(saved: string | null | undefined, languages: readonly string[]): Locale {
  if (saved === "en" || saved === "ru") return saved;
  for (const language of languages) {
    const base = language.toLowerCase().split("-")[0];
    if (base === "ru") return "ru";
    if (base === "en") return "en";
  }
  return "en";
}

let activeLocale: Locale = resolveLocale(storedLocale(), browserLanguages());

export function currentLocale(): Locale {
  return activeLocale;
}

export function setLocale(locale: Locale): void {
  activeLocale = locale;
  try {
    globalThis.localStorage?.setItem(LOCALE_KEY, locale);
  } catch {
    void 0;
  }
  if (typeof document !== "undefined") document.documentElement.lang = locale;
}

export function applyDocumentLocale(): void {
  if (typeof document !== "undefined") document.documentElement.lang = activeLocale;
}

export function translate(locale: Locale, message: string, values: MessageValues = {}): string {
  const template = locale === "ru" ? (ruMessages[message] ?? message) : message;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

export function t(message: string, values: MessageValues = {}): string {
  return translate(activeLocale, message, values);
}

