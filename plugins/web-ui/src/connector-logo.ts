export function connectorLogo(id: string, logoUrl?: string): TemplateResult {
  const logo = CONNECTOR_LOGOS[id];
  if (!logo && logoUrl && /^https:\/\/logos\.composio\.dev\/api\/[a-z0-9_-]{1,100}$/.test(logoUrl)) {
    return html`<span class="connector-logo connector-logo-remote" aria-hidden="true"
      >${icon(Plug, 18)}<img
        src=${logoUrl}
        alt=""
        width="18"
        height="18"
        loading="lazy"
        referrerpolicy="no-referrer"
        @error=${(event: Event) => {
          (event.currentTarget as HTMLImageElement).hidden = true;
        }}
    /></span>`;
  }
  if (!logo) return html`<span class="connector-logo">${icon(Plug, 18)}</span>`;
  return html`<span class="connector-logo" data-service=${id}
    ><svg width="18" height="18" viewBox=${logo.viewBox} fill="currentColor" aria-hidden="true" focusable="false">
      ${logo.paths.map(([d, fill]) => svg`<path d=${d} fill=${fill ?? "currentColor"}></path>`)}
    </svg></span
  >`;
}
